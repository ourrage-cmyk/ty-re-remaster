# Generates tex_tags.inc (embedded texture tags) from RESEARCH\recording\texture_tags.csv + RESEARCH\rkv_index\Data_PC.csv
# kTagNames[]: lowercase file name + flags (1 known, 2 emissive, 4 transparent, 8 character; rkv dds not in the list get flags 0);
# kRkvDds[]: Data_PC.rkv offset/size -> index into kTagNames (sorted by offset)
$csv = Import-Csv C:\CLAUDE\RESEARCH\recording\texture_tags.csv -Header path,name,emissive,transparent,character | select -skip 1
$h = @{}; $names = New-Object System.Collections.ArrayList
foreach ($r in $csv) {
    $f = 1; if ($r.emissive -eq 'yes') { $f += 2 }; if ($r.transparent -eq 'yes') { $f += 4 }; if ($r.character -eq 'yes') { $f += 8 }
    $n = $r.name.ToLower(); $h[$n] = $names.Count; [void]$names.Add(@($n, $f))
}
$d = Import-Csv C:\CLAUDE\RESEARCH\rkv_index\Data_PC.csv | ? { $_.Path -like '*.dds' } | % { [pscustomobject]@{ off = [uint32]$_.Offset; size = [uint32]$_.Size; n = (Split-Path $_.Path -Leaf).ToLower() } } | sort off
foreach ($e in $d) { if (-not $h.ContainsKey($e.n)) { $h[$e.n] = $names.Count; [void]$names.Add(@($e.n, 0)) } }
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// generated by gen_tex_tags.ps1 - do not edit')
[void]$sb.AppendLine('struct TagName { const char* n; unsigned char f; }; struct RkvDds { unsigned off, size; unsigned short idx; };')
[void]$sb.AppendLine('static const TagName kTagNames[] = {')
foreach ($e in $names) { [void]$sb.AppendLine("{`"$($e[0])`",$($e[1])},") }
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('static const RkvDds kRkvDds[] = {')
foreach ($e in $d) { [void]$sb.AppendLine("{$($e.off)u,$($e.size)u,$($h[$e.n])},") }
[void]$sb.AppendLine('};')
[IO.File]::WriteAllText('C:\CLAUDE\SRC\agents\tess\tex_tags.inc', $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
"names $($names.Count) rkv entries $($d.Count)"
